// yarn contracts:types
//
// Writes src/lib/contracts/types.ts from contracts/openapi/survey-api.v1.yaml: the request and response
// types, and the error catalogue the survey site shows. tests/contracts/generated-types.test.ts fails
// when the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { parse } from "yaml";

export const outputPath = "src/lib/contracts/types.ts";
const specPath = "contracts/openapi/survey-api.v1.yaml";

export async function generateContractTypes(): Promise<string> {
  const types = astToString(await openapiTS(pathToFileURL(specPath)));
  const catalogue = parse(readFileSync(specPath, "utf8"))["x-error-catalogue"] as Record<string, { status: number; message: string; action: string }>;

  return [
    "// Generated by `yarn contracts:types` from contracts/openapi/survey-api.v1.yaml. Do not edit.",
    "",
    types.trim(),
    "",
    "export type ErrorCode = components[\"schemas\"][\"ErrorCode\"];",
    "",
    "/** Each error code's message and action, from x-error-catalogue. */",
    `export const errorCatalogue: Record<ErrorCode, { status: number; message: string; action: string }> = ${JSON.stringify(catalogue, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  writeFileSync(outputPath, await generateContractTypes());
  console.log(`Wrote ${outputPath}`);
}
